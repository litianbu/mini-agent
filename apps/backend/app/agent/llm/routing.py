"""模型路由：哪个角色该用哪个模型。

现在只有两个角色，但分成两层是有意义的：

    角色（role）      —— 业务视角："这是谁在干活"
    模型（model）     —— 实现视角："用哪个具体模型"

S9-1 之前，这两层是焊死的：代码里到处直接读 `settings.llm_model`。
想给"子 agent 用便宜模型"就得在每个调用点写 if —— 那是最难改的写法。

**为什么值得做路由**（三条真实的权衡，不是理论）：

  1. 成本 —— 便宜模型能干的活别用贵的。
     一次 agent 请求内部最多 8 轮模型调用，每轮都带上万 token 的历史，
     子 agent 还要再来一遍。**单价差 10 倍，账单就差 10 倍。**
  2. 延迟 —— 小模型通常首字更快，简单任务用户体验更好
  3. 能力 —— 难的活需要强模型。**便宜模型做错事，比用贵的更贵**
     （它会在 8 轮里反复试错，最后还是失败）

反过来，**路由也会带来一个新问题**：同一个会话里前后用的模型不一样，
风格会跳变。所以路由要按"角色"分，不是按"单条消息有多难"——
后者需要判断，判断本身又要花一次模型调用，得不偿失。
"""

from __future__ import annotations

from ...core.config import settings

__all__ = ["MAIN", "SUB", "resolve"]

# 主 agent：和用户对话、做决策、调工具的那个
MAIN = "main"

# 子 agent：被派去执行子任务的（S9-3 才会有真正的调用方）
SUB = "sub"


def resolve(role: str = MAIN) -> str:
    """角色 → 具体模型名。

    两条规则值得注意：

    **① 未知角色回落到主模型，不报错。**
       role 是内部字符串，写错是代码 bug。但为了一个拼写错误
       让整个对话崩掉不值得 —— 回落到主模型，行为退化成"没有路由"，
       比抛异常好。真写 bug 了，日志和测试会发现。

    **② 子 agent 的模型可以不配。**
       `llm_model_sub` 留空就沿用主模型。这样：
       · 只有一套模型的用户（比如现在）什么都不用改
       · 想省钱时填一个便宜模型名就行，代码不用动
       **"缺省值为空 = 沿用上一个"** 是配置项设计的常用手法，
       比"必须配两个模型"友好得多。
    """
    if role == SUB:
        # .strip() 防的是空字符串（不是 None）——
        # .env 里写 `LLM_MODEL_SUB=` 读出来是 ""，不是 None
        return settings.llm_model_sub.strip() or settings.llm_model

    return settings.llm_model
